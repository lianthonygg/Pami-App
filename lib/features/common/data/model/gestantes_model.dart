import 'package:pami_app/features/common/domain/entities/gestante.dart';

class GestantesModel extends Gestante {
  GestantesModel({
    required super.id,
    required super.nombre,
    required super.ci,
    required super.personaId,
    required super.direccionDelCi,
    required super.direccionEnQueVive,
    required super.telefono,
    required super.antPP,
    required super.observaciones,
    required super.tgCaptacion,
    required super.tgFinal,
    required super.fum,
    required super.gestaciones,
    required super.partos,
    required super.abortos,
    required super.cesareas,
    required super.antPPretermino,
    required super.fechaCaptacion,
    required super.fechaProbableParto,
    required super.rciu,
    required super.imc,
    required super.clasificacionRiesgo,
    required super.lastModified,
    required super.isAvailable,
  });

  factory GestantesModel.fromJson(Map<String, dynamic> json) => GestantesModel(
    id: json['id'],
    nombre: json['nombre'],
    ci: json['ci'],
    personaId: json['personaId'],
    direccionDelCi: json['direccionDelCi'],
    direccionEnQueVive: json['direccionEnQVive'],
    telefono: json['telefono'],
    antPP: json['antPp'],
    observaciones: json['observaciones'],
    tgCaptacion: json['tgCaptacion'],
    tgFinal: json['tgFinal'],
    fum: DateTime.parse(json['fum']),
    gestaciones: json["gestaciones"],
    partos: json['partos'],
    abortos: json["abortos"],
    cesareas: json['cesareas'],
    antPPretermino: json["antPPretermino"],
    fechaCaptacion: DateTime.parse(json['fechaCaptacion']),
    fechaProbableParto: DateTime.parse(json["fechaProbableParto"]),
    rciu: json['rciu'],
    imc: json["imc"],
    clasificacionRiesgo: json['clasificacionRiesgo'],
    lastModified: DateTime.parse(json['lastModified']),
    isAvailable: json['isAvailable'],
  );
}
